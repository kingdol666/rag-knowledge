"""Assemble a KBS/Elsevier submission package with NO subfolders (Editorial
Manager cannot process LaTeX submissions that contain subdirectories).

Output: paper-kbs/submission/
  * manuscript sources at one folder level (main2.tex + n*.tex + tab_*.tex)
  * refs.bib + the generated main2.bbl (both are 'Manuscript' item types)
  * every figure as a separate file at the same level
  * highlights.docx (Elsevier: 3-5 bullets, <=85 chars each, Word document)
  * README-submission.md describing the mapping and the author action items

Run after the manuscript build so that main2.bbl is current:
    python paper-kbs/submission/make_submission_package.py
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

TEX = Path(__file__).resolve().parents[1] / "tex"
OUT = Path(__file__).resolve().parent

SOURCE_TEX = [
    "main2.tex",
    "n1_intro.tex",
    "n2_related.tex",
    "n3_overview.tex",
    "n4_acquisition.tex",
    "n5_organization.tex",
    "n6_retrieval.tex",
    "n7_implementation.tex",
    "n8a_eval.tex",
    "n8b_eval.tex",
    "n8c_eval.tex",
    "n9_discussion.tex",
    "n10_threats.tex",
    "n11_conclusion.tex",
    "n_back.tex",
    "n_appendix_tables.tex",
    "tab_appendix_ranks.tex",
    "highlights.tex",
]
SOURCE_BIB = ["refs.bib", "refs_new_verified.bib"]
SOURCE_OTHER = ["main2.bbl"]


def highlights() -> list[str]:
    text = (TEX / "highlights.tex").read_text(encoding="utf-8")
    body = re.search(r"\\begin\{highlights\}(.*?)\\end\{highlights\}", text, re.S)
    if not body:
        raise SystemExit("highlights.tex has no highlights environment")
    items = [re.sub(r"\s+", " ", m.group(1)).strip()
             for m in re.finditer(r"\\item\s+(.*?)(?=\\item|$)", body.group(1), re.S)]
    return items


def write_docx(items: list[str], path: Path) -> None:
    from docx import Document  # type: ignore

    doc = Document()
    doc.add_heading("Highlights", level=1)
    for item in items:
        doc.add_paragraph(item, style="List Bullet")
    doc.save(path)


def main() -> int:
    items = highlights()
    bad = [(i, s) for i, s in enumerate(items, 1) if len(s) > 85]
    print(f"highlights: {len(items)} item(s), longest {max(len(s) for s in items)} chars")
    for i, s in enumerate(items, 1):
        print(f"  {i}. ({len(s)}) {s}")
    if bad or not (3 <= len(items) <= 5):
        print("FAIL: Elsevier requires 3-5 bullets of at most 85 characters", file=sys.stderr)
        return 1

    OUT.mkdir(parents=True, exist_ok=True)
    copied: list[str] = []
    for group in (SOURCE_TEX, SOURCE_BIB, SOURCE_OTHER):
        for name in group:
            src = TEX / name
            if not src.exists():
                print(f"  ! missing (skipped): {name}", file=sys.stderr)
                continue
            shutil.copy2(src, OUT / name)
            copied.append(name)

    # figures: flatten tex/figs/* into the package root, same base names
    figs = sorted((TEX / "figs").glob("*.pdf"))
    for f in figs:
        shutil.copy2(f, OUT / f.name)

    # the submission copy must not rely on a graphics subfolder
    main = OUT / "main2.tex"
    text = main.read_text(encoding="utf-8")
    stripped = re.sub(r"\\graphicspath\{\{[^}]*\}\}\n?", "", text)
    if stripped != text:
        main.write_text(stripped, encoding="utf-8")
        print("  main2.tex: removed \\graphicspath (figures sit at the same level)")

    write_docx(items, OUT / "highlights.docx")

    (OUT / "README-submission.md").write_text(
        "# KBS submission package\n\n"
        "Generated by `make_submission_package.py`. Everything sits at ONE folder level, as\n"
        "Editorial Manager cannot process LaTeX submissions that contain subfolders.\n\n"
        f"- manuscript sources: {', '.join(n for n in copied if n.endswith('.tex'))}\n"
        "- bibliography: `refs.bib` + `refs_new_verified.bib`, and the generated `main2.bbl`\n"
        "  (upload the `.bbl`, not only the `.bib`: .tex, .bbl, .bst, .sty, .cls are all\n"
        "  'Manuscript' item types)\n"
        f"- figures: {len(figs)} vector PDFs, one file per figure, same base names as the\n"
        "  `\\includegraphics` calls: " + ", ".join(f.name for f in figs) + "\n"
        "- `highlights.docx`: 3-5 bullets, each at most 85 characters, no jargon\n"
        "- `highlights.tex`: the same bullets for the `highlights` environment\n\n"
        "## Author actions before upload (not automatable)\n\n"
        "1. Replace the author placeholders in `main2.tex` (`Author Name`, `Co-author Name`,\n"
        "   affiliation, `author@example.com`) and the three `AUTHOR ACTION` markers.\n"
        "2. Complete Elsevier's declaration of competing interests at\n"
        "   declarations.elsevier.com, export it as .doc/.docx, and upload it separately.\n"
        "3. Confirm the funding sentence in `n_back.tex` and add ORCIDs where the submission\n"
        "   system asks for them (the KBS guide itself does not mandate ORCID in the PDF).\n"
        "4. Optional: graphical abstract is NOT required by KBS; if supplied it must be\n"
        "   1328x531 px minimum, 300 dpi, RGB, fonts Arial/Times/Courier/Symbol.\n",
        encoding="utf-8",
    )
    print(f"package written to {OUT} ({len(copied)} sources + {len(figs)} figures)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
