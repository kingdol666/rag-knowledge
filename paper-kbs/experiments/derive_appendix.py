#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Derive the per-question appendix table (tex/tab_appendix_ranks.tex).

Columns: the seven tool-layer pipelines (exp1 logs) plus the two derived
configurations (exp5 replay, same logged hybrid pools as Fig 6b).
Cell = best gold rank in the top-5 window, '--' if the gold was not there.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kbcommon import QUESTIONS, RESULTS

HERE = Path(__file__).resolve().parent.parent  # paper-kbs/
TEXDIR = HERE / "tex"

E5_METHODS = {"filter_only", "rrf_fuse"}
DISPLAY = [("bm25", "BM25"), ("dense", "Dense"), ("rrf", "RRF"),
           ("graph", "Graph"), ("twostage", "2-stage"),
           ("fusion_only", "Fusion"), ("qdcvr_hybrid", "Hybrid"),
           ("filter_only", "Filter"), ("rrf_fuse", "RRF-fuse")]
BS = "\\"


def cell(rank) -> str:
    return "--" if not rank else str(int(rank))


def main() -> int:
    e1 = json.loads((RESULTS / "exp1_retrieval.json").read_text(
        encoding="utf-8"))["rows"]
    e5 = json.loads((RESULTS / "exp5_judge_filter.json").read_text(
        encoding="utf-8"))["rows"]
    m1 = {(r["method"], r["qid"]): r["best_rank"] for r in e1}
    m5 = {r["qid"]: r for r in e5}
    qids = [q["qid"] for q in QUESTIONS]
    assert len(m1) == 7 * 16 and len(m5) == 16

    row_end = " \\" + BS

    lines = [
        "% Auto-generated by experiments/derive_appendix.py -- do not edit.",
        BS + "begin{table}[t]",
        BS + "centering",
        BS + "scriptsize",
        BS + "setlength{" + BS + "tabcolsep}{5.5pt}",
        BS + "caption{Per-question best gold rank (top-5 window; `--' = gold"
        " absent) for the seven tool-layer pipelines (logged runs) and the"
        " two derived configurations (offline replay of the same logged"
        " QDCVR-Hybrid pools as Fig.~" + BS + "ref{fig:marginvariants})."
        " Fusion = fusion-only (no judge); Hybrid = the shipped"
        " QDCVR-Hybrid judged ordering; Filter = judge-as-filter."
        " Question numbers and texts: Table~" + BS + "ref{tab:questions}.}",
        BS + "label{tab:appendixranks}",
        BS + "begin{tabular}{l" + "c" * len(DISPLAY) + "}",
        BS + "toprule",
        "Q & " + " & ".join(n for _, n in DISPLAY) + row_end,
        BS + "midrule",
    ]
    for qid in qids:
        cells = []
        for meth, _ in DISPLAY:
            if meth in E5_METHODS:
                cells.append(cell(m5[qid][meth]["best_rank"]))
            else:
                cells.append(cell(m1[(meth, qid)]))
        lines.append(f"{qid[1:]} & " + " & ".join(cells) + row_end)
    lines += [BS + "bottomrule", BS + "end{tabular}", BS + "end{table}", ""]
    out = TEXDIR / "tab_appendix_ranks.tex"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("wrote", out, f"({len(qids)} rows x {len(DISPLAY)} methods)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
